def astar(graph_edges, start, goal):
    open_set = []
    heapq.heapify(open_set)
    count = 0  # Tiebreaker for heap

    g_score = {start: 0}
    f_score = {start: distance(start, goal)}
    came_from = {}

    heapq.heappush(open_set, (f_score[start], count, start))
    visited = set()

    while open_set:
        _, _, current = heapq.heappop(open_set)

        if current == goal:
            # print("Goal reached!")
            return reconstruct_path(came_from, current)

        visited.add(current)

        for neighbor, cost in graph_edges.get(current, []):
            if neighbor in visited:
                continue

            tentative_g = g_score[current] + cost

            if tentative_g < g_score.get(neighbor, float('inf')):
                came_from[neighbor] = current
                g_score[neighbor] = tentative_g
                f_score[neighbor] = tentative_g + distance(neighbor, goal)
                count += 1
                heapq.heappush(open_set, (f_score[neighbor], count, neighbor))

    print("No path found.")
    return []

def reconstruct_path(came_from, current):
    path = [current]
    while current in came_from:
        current = came_from[current]
        path.append(current)
    path.reverse()
    return path
        

def remove_consecutive_duplicates(path):
    if not path:
        return []
    cleaned = [path[0]]
    for point in path[1:]:
        if point != cleaned[-1]:
            cleaned.append(point)
    return cleaned

def generate_continuous_path(sparse_path, grid, turning_radius=5, step_size=0.5):
    """
    Convert a sparse PRM path into a continuous Ackermann-feasible path,
    while checking for collisions with obstacles.
    """
    if not sparse_path or len(sparse_path) < 2:
        return sparse_path

    continuous_path = []
    for i in range(len(sparse_path) - 1):
        start = sparse_path[i]
        end = sparse_path[i + 1]

        # Check if the curved path between them is valid
        if ackermann_collision_check(start, end, grid, turning_radius, step_size):
            segment = ackermann_path(start, end, turning_radius, step_size)
            if continuous_path:
                segment = segment[1:]  # remove duplicate
            continuous_path.extend(segment)
        else:
            # print(f"Skipping segment {start} → {end} due to collision.")
            pass

    return remove_consecutive_duplicates(continuous_path)
        